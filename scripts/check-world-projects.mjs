import {chromium} from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
if(await page.locator('.public-work .project').count()!==12)throw Error('Initial page should display 12 projects');
await page.getByRole('button',{name:'Load more projects'}).click();
if(await page.locator('.public-work .project').count()!==24)throw Error('Load more failed');
await page.getByRole('button',{name:'Games',exact:true}).click();
if(!(await page.locator('.public-work .project').count()))throw Error('Games category empty');
await page.getByRole('button',{name:'All projects',exact:false}).click();
await page.getByLabel('Search public projects').fill('SNIPER-SHADOW');
if(await page.locator('.public-work .project').count()!==1)throw Error('Project search failed');
await page.getByRole('button',{name:'Live demo',exact:true}).click();
const frame=page.locator('.public-demo-modal iframe');await frame.waitFor();
if(!(await frame.getAttribute('src')).includes('sniper-shadow-one.vercel.app'))throw Error('Wrong demo URL');
if(!(await frame.getAttribute('sandbox')).includes('allow-forms'))throw Error('Demo forms blocked');
await page.getByRole('button',{name:'Mobile preview',exact:true}).click();
if(!await page.locator('.mobile-frame').count())throw Error('Mobile preview toggle failed');
if((await page.locator('.live-demo-toolbar a').getAttribute('target'))!=='_blank')throw Error('Full app fallback missing');
await page.getByRole('button',{name:'Close project preview'}).click();
await page.getByLabel('Search public projects').fill('Brand-Kit');
await page.getByRole('button',{name:'Project details',exact:true}).click();
await page.getByRole('link',{name:'View GitHub source'}).waitFor();
await page.keyboard.press('Escape');
await page.getByLabel('Search public projects').fill('a-project-that-does-not-exist');
await page.getByText('No matching projects').waitFor();
await page.getByRole('button',{name:'Clear filters'}).click();
await page.getByLabel('Live apps only').check();
if(await page.locator('.public-work .project').count()!==11)throw Error('Expected 11 verified live apps');
await page.screenshot({path:'evidence/world-public-projects-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
await page.getByLabel('Search public projects').fill('Nexagen');
await page.getByRole('button',{name:'Live demo',exact:true}).click();
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile modal overflow');
await page.getByRole('button',{name:'Close project preview'}).click();
await page.screenshot({path:'evidence/world-public-projects-mobile.png',fullPage:true});
if(errors.length)throw Error(errors.join('\n'));
console.log('Passed: 70-project gallery, pagination, search, categories, 11 live apps, embedded URLs, mobile preview, GitHub source, Escape, empty results, and mobile overflow.');
}finally{await browser.close()}
