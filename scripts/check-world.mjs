import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.screenshot({path:'evidence/world-agency-desktop.png',fullPage:true});
await page.getByRole('button',{name:'AI Tools',exact:true}).click();
if(await page.locator('.project').count()!==1)throw Error('Category filter failed');
await page.getByRole('button',{name:'Live demo',exact:true}).click();
await page.frameLocator('iframe').getByLabel('Your idea').fill('A reading app');
await page.frameLocator('iframe').getByRole('button',{name:'Explore idea'}).click();
await page.frameLocator('iframe').getByRole('status').waitFor();
await page.getByRole('button',{name:'Close preview',exact:true}).click();
await page.getByRole('button',{name:'Toggle color theme'}).click();
if(await page.locator('html').getAttribute('data-theme')!=='light')throw Error('Theme failed');
await page.getByRole('button',{name:'Toggle color theme'}).click();
await page.getByRole('button',{name:'Open World Agentic assistant'}).click();
await page.getByLabel('Message the assistant').fill('I want to order a project');
await page.getByRole('button',{name:'Send message'}).click();
await page.getByRole('button',{name:'Cancel',exact:true}).click();
await page.getByText('Your request has been cancelled in this chat.').waitFor();
await page.locator('.chat-panel').getByRole('button',{name:'Close assistant',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
await page.screenshot({path:'evidence/world-agency-mobile.png',fullPage:true});
await page.getByRole('button',{name:'Toggle navigation'}).click();
await page.locator('nav').getByRole('link',{name:'Services',exact:true}).click();
if(await page.locator('nav').getAttribute('class')!=='nav')throw Error('Mobile menu did not close');
await browser.close();if(errors.length)throw Error(errors.join('\n'));
console.log('Passed: filters, embedded demo, themes, order cancellation, mobile navigation, overflow, and browser errors.');
